<?php
/**
 * A prebuilt cache of the classes in a module directory.
 *
 * @package TenupFramework
 */

declare( strict_types = 1 );

namespace TenupFramework;

use FilesystemIterator;
use RecursiveDirectoryIterator;
use RecursiveIteratorIterator;
use Spatie\StructureDiscoverer\Discover;

/**
 * Reads and writes `class-loader-cache/classes.php`, the class list a build step
 * generates for a directory so a request never has to discover it.
 *
 * Discovery tokenizes every PHP file in the directory, which costs about half a
 * millisecond per file on every request wherever the runtime cache can't be
 * written (WordPress VIP, other read-only hosts). A build step runs
 * `vendor/bin/wp-framework-cache <dir>` once, ships the file with the code, and
 * ModuleInitialization reads it on any host. The file records a hash of the
 * directory's PHP files, so it is only used while it matches the code it lists.
 *
 * @package TenupFramework
 */
final class ClassCache {

	/**
	 * Folder, inside the module directory, that holds the cache.
	 */
	public const DIRECTORY = 'class-loader-cache';

	/**
	 * File name of the prebuilt cache.
	 */
	public const FILE = 'classes.php';

	/**
	 * Path of the prebuilt cache file for a directory.
	 *
	 * @param string $dir The module directory.
	 *
	 * @return string
	 */
	public static function path( string $dir ): string {
		return rtrim( $dir, '/\\' ) . '/' . self::DIRECTORY . '/' . self::FILE;
	}

	/**
	 * Hash of a directory's PHP files: their paths relative to the directory and
	 * their contents. Modification times are left out on purpose, since a deploy
	 * rewrites them without changing the code.
	 *
	 * @param string $dir The module directory.
	 *
	 * @return string
	 */
	public static function hash( string $dir ): string {
		$root  = rtrim( $dir, '/\\' );
		$files = [];

		$iterator = new RecursiveIteratorIterator(
			new RecursiveDirectoryIterator( $root, FilesystemIterator::SKIP_DOTS )
		);

		foreach ( $iterator as $file ) {
			if ( ! $file instanceof \SplFileInfo || 'php' !== $file->getExtension() ) {
				continue;
			}

			$relative = substr( $file->getPathname(), strlen( $root ) + 1 );

			if ( str_starts_with( $relative, self::DIRECTORY . DIRECTORY_SEPARATOR ) ) {
				continue;
			}

			$files[ $relative ] = $file->getPathname();
		}

		ksort( $files );

		$context = hash_init( 'md5' );

		foreach ( $files as $relative => $path ) {
			hash_update( $context, $relative . "\0" );
			hash_update_file( $context, $path );
		}

		return hash_final( $context );
	}

	/**
	 * The cached classes for a directory, or null when there is no prebuilt cache
	 * or it no longer matches the directory's code.
	 *
	 * @param string      $dir  The module directory.
	 * @param string|null $hash The directory's hash, when the caller already has it.
	 *
	 * @return array<string>|null
	 */
	public static function read( string $dir, ?string $hash = null ): ?array {
		$path = self::path( $dir );

		if ( ! is_readable( $path ) ) {
			return null;
		}

		$cache = include $path;

		if ( ! is_array( $cache ) || ! isset( $cache['hash'], $cache['classes'] ) || ! is_array( $cache['classes'] ) ) {
			return null;
		}

		if ( ( $hash ?? self::hash( $dir ) ) !== $cache['hash'] ) {
			return null;
		}

		return array_values( array_filter( $cache['classes'], 'is_string' ) );
	}

	/**
	 * Discover a directory's classes and write them to its prebuilt cache.
	 *
	 * Runs without WordPress, so it can be called from a build step.
	 *
	 * @param string $dir The module directory.
	 *
	 * @throws \RuntimeException If the directory doesn't exist or the cache can't be written.
	 *
	 * @return array<string> The classes written.
	 */
	public static function write( string $dir ): array {
		if ( ! is_dir( $dir ) ) {
			// phpcs:ignore WordPress.Security.EscapeOutput.ExceptionNotEscaped
			throw new \RuntimeException( 'Directory "' . $dir . '" does not exist.' );
		}

		$classes = array_values(
			array_filter(
				Discover::in( $dir )->classes()->withoutChains()->get(),
				'is_string'
			)
		);
		sort( $classes );

		$path   = self::path( $dir );
		$folder = dirname( $path );

		// phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_mkdir
		if ( ! is_dir( $folder ) && ! mkdir( $folder, 0755, true ) && ! is_dir( $folder ) ) {
			// phpcs:ignore WordPress.Security.EscapeOutput.ExceptionNotEscaped
			throw new \RuntimeException( 'Could not create "' . $folder . '".' );
		}

		$contents = "<?php\n// Generated by wp-framework-cache. Do not edit; regenerate it when the code changes.\n\nreturn "
			// phpcs:ignore WordPress.PHP.DevelopmentFunctions.error_log_var_export
			. var_export(
				[
					'hash'    => self::hash( $dir ),
					'classes' => $classes,
				],
				true
			)
			. ";\n";

		// phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_file_put_contents
		if ( false === file_put_contents( $path, $contents ) ) {
			// phpcs:ignore WordPress.Security.EscapeOutput.ExceptionNotEscaped
			throw new \RuntimeException( 'Could not write "' . $path . '".' );
		}

		return $classes;
	}
}
